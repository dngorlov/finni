/**
 * Packs the shop item pictures (design/items/<name>.png, 16 × 16 RGBA) into
 * src/ui/components/itemSprites.generated.ts, in the same run-length format as
 * the pet frames (see slice-pet-sheets.mjs), so Магазин draws them as SVG
 * squares (ItemSprite) and they stay crisp on Android at any size.
 *
 * Encoding: 16 rows joined by "/"; a row is runs of `<colour><length>`, where
 * colour is "." (transparent) or a digit indexing the palette, and length is
 * one base-36 digit. A transparent tail of a row is left out.
 *
 * Re-run after new item art:
 *   node scripts/pack-item-sprites.mjs
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { PNG } from "pngjs";

const repoRoot = join(dirname(fileURLToPath(import.meta.url)), "..");
const sourceDir = join(repoRoot, "design", "items");
const generatedFile = join(repoRoot, "src", "ui", "components", "itemSprites.generated.ts");

const SIDE = 16;

function hex(value) {
  return value.toString(16).padStart(2, "0").toUpperCase();
}

function encode(png, file) {
  const palette = [];
  const rows = [];
  const colourAt = (x, y) => {
    const i = (y * png.width + x) * 4;
    if (png.data[i + 3] === 0) return ".";
    if (png.data[i + 3] !== 255) throw new Error(`${file}: half-transparent pixel at ${x},${y}`);
    const key = `#${hex(png.data[i])}${hex(png.data[i + 1])}${hex(png.data[i + 2])}`;
    let index = palette.indexOf(key);
    if (index < 0) {
      palette.push(key);
      index = palette.length - 1;
    }
    if (index > 9) throw new Error(`${file}: more than 10 colours`);
    return String(index);
  };
  for (let y = 0; y < SIDE; y += 1) {
    const runs = [];
    let x = 0;
    while (x < SIDE) {
      const colour = colourAt(x, y);
      let length = 1;
      while (x + length < SIDE && colourAt(x + length, y) === colour) length += 1;
      runs.push(colour + length.toString(36));
      x += length;
    }
    if (runs.length > 0 && runs[runs.length - 1].startsWith(".")) runs.pop();
    rows.push(runs.join(""));
  }
  return { palette, frames: [rows.join("/")] };
}

const sprites = [];
for (const file of readdirSync(sourceDir).sort()) {
  if (!file.endsWith(".png")) continue;
  const png = PNG.sync.read(readFileSync(join(sourceDir, file)));
  if (png.width !== SIDE || png.height !== SIDE) {
    throw new Error(`${file}: ${png.width}×${png.height} is not ${SIDE}×${SIDE}`);
  }
  sprites.push({ name: file.slice(0, -".png".length), ...encode(png, file) });
  console.log(`${file} → ${file.slice(0, -".png".length)}`);
}

const lines = [
  "// Generated by scripts/pack-item-sprites.mjs — do not edit by hand.",
  'import type { PetPixels } from "../pet/petSprites.generated";',
  "",
  "/** Side of one shop item picture, in art pixels. */",
  `export const ITEM_ART_PX = ${SIDE};`,
  "",
  "/** Shop item pictures from design/items, keyed by file name. One frame each. */",
  "export const ITEM_SPRITES = {",
  ...sprites.map(
    ({ name, palette, frames }) =>
      `  ${name}: {\n    palette: ${JSON.stringify(palette)},\n    frames: [${JSON.stringify(frames[0])}],\n  },`,
  ),
  "} satisfies Record<string, PetPixels>;",
  "",
  "export type ItemSpriteName = keyof typeof ITEM_SPRITES;",
  "",
];
writeFileSync(generatedFile, lines.join("\n"));
console.log(`${sprites.length} item sprites written`);
